import json
from fastapi import APIRouter, HTTPException
from fastapi.responses import FileResponse
from ..config import OUT_REPORTS
from ..schemas.analysis import ReportDocument
from ..services import report_generator as R
from .analysis import history

router = APIRouter(prefix="/api/reports", tags=["reports"])

@router.post("", status_code=201, response_model=ReportDocument)
def create():
    """Build a report from the current dataset, detection history, and processing log.

    Sections with no runs stay empty. Calibration parameters are copied from the last
    run and are omitted from that run unless it was valid. Nothing is simulated.
    """
    return R.build(history()[-20:])

@router.get("")
def list_reports():
    """Report ids, newest filename order is not guaranteed; ids sort alphabetically."""
    return sorted(p.stem for p in OUT_REPORTS.glob("*.json"))

@router.get("/{report_id}", response_model=ReportDocument)
def get(report_id: str):
    """JSON report previously generated by POST /api/reports."""
    p = R.path(report_id)
    if not p:
        raise HTTPException(404, "Report not found")
    return json.loads(p.read_text(encoding="utf-8"))

@router.get("/{report_id}/download")
def download(report_id: str, format: str = "html"):
    """Download the HTML or JSON report. `format` is `html` (default) or `json`."""
    if format not in ("html", "json"):
        raise HTTPException(422, "format must be html or json")
    p = R.path(report_id, format)
    if not p:
        raise HTTPException(404, "Report not found")
    return FileResponse(p, filename=f"saffire-report-{report_id}.{format}")
